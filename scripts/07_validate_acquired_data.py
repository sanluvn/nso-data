def main() -> None:
    heading("ACQUIRED-DATA STRUCTURAL VALIDATION")

    print(f"Project root                         : {PROJECT_ROOT}")
    print("Network requests                     : NO")
    print("Production acquisition               : NOT RUN")
    print("Registry/manifest/raw modifications  : NO")
    print("Cross-source fuzzy mapping           : NO")

    # ---------------------------------------------------------------------
    # PX
    # ---------------------------------------------------------------------
    heading("A — PX-WEB PERSISTED TABLES")
    px_results = validate_all_px()
    px_summary = report_px(px_results)

    # ---------------------------------------------------------------------
    # Website
    # ---------------------------------------------------------------------
    heading("B — NSO WEBSITE: PRODUCTION INVENTORY + RECENT WORKBOOKS")

    manifests = production_manifests()
    excel_records = current_excel_inventory(manifests)

    suffix_counts = Counter(r["path"].suffix.casefold() for r in excel_records)
    resolution_counts = Counter(r["resolution_mode"] for r in excel_records)

    print(f"Current Excel suffix distribution    : {dict(sorted(suffix_counts.items()))}")
    print(f"Path resolution modes                : {dict(sorted(resolution_counts.items()))}")

    website_summary = inspect_recent_workbooks(excel_records)

    # ---------------------------------------------------------------------
    # Assumption audit
    # ---------------------------------------------------------------------
    heading("C — STRUCTURAL AUDIT")

    audit = structural_audit(px_summary, website_summary)
    review_rows = []

    for assumption, status, evidence in audit:
        print(f"[{status}] {assumption}")
        print(f"       {evidence}")
        if status != "PASS":
            review_rows.append((assumption, evidence))

    # ---------------------------------------------------------------------
    # Decision
    # ---------------------------------------------------------------------
    heading("VALIDATION DECISION")

    print(f"PX tables validated                   : {px_summary['table_count']}")
    print(f"PX persisted rows validated           : {px_summary['total_rows']:,}")
    print(
        f"PX dimension-count range              : "
        f"{px_summary['min_dim']}..{px_summary['max_dim']}"
    )
    print(f"Production Website manifests          : {len(manifests)}")
    print(f"Current Website Excel artifacts       : {len(excel_records)}")
    print(f"Recent Website XLSX structurally read : {website_summary['readable']}")
    print(f"Structural checks needing review      : {len(review_rows)}")

    if review_rows:
        print("\nREVIEW REQUIRED — acquired-data structural checks exposed exceptions:")
        for assumption, evidence in review_rows:
            print(f"- {assumption}")
            print(f"  {evidence}")

        raise RuntimeError(
            "Acquired-data validation exposed one or more structural checks "
            "requiring review."
        )

    print("\nPASS — current persisted PX-Web and representative NSO Website")
    print("artifacts satisfy the acquisition structural checks.")
    print("")
    print("IMPORTANT:")
    print("- This PASS validates persisted source structure and readability.")
    print("- It does not assert cross-source semantic equivalence.")


if __name__ == "__main__":
    main()
