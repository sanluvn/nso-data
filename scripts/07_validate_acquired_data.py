def heading(title: str) -> None:
    print("\n" + "=" * 100)
    print(title)
    print("=" * 100)


def subheading(title: str) -> None:
    print("\n" + title)
    print("-" * 100)


def norm_text(value: Any) -> str:
    if value is None:
        return ""
    text = " ".join(str(value).split()).casefold()
    text = unicodedata.normalize("NFD", text)
    text = "".join(ch for ch in text if unicodedata.category(ch) != "Mn")
    text = text.replace("³", "3").replace("²", "2")
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def compact_text(value: Any) -> str:
    return re.sub(r"[^a-z0-9]+", "", norm_text(value))


def load_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as fh:
        obj = json.load(fh)
    if not isinstance(obj, dict):
        raise ValueError(f"Expected JSON object: {path}")
    return obj


def parse_date(value: Any) -> datetime:
    if not isinstance(value, str):
        return datetime.min
    text = value.strip()
    try:
        dt = datetime.fromisoformat(text.replace("Z", "+00:00"))
        return dt.replace(tzinfo=None) if dt.tzinfo else dt
    except ValueError:
        pass
    for fmt in ("%Y-%m-%d", "%d/%m/%Y", "%d-%m-%Y"):
        try:
            return datetime.strptime(text, fmt)
        except ValueError:
            pass
    return datetime.min


def safe_rel(path: Path) -> str:
    try:
        return str(path.relative_to(PROJECT_ROOT))
    except ValueError:
        return str(path)


def scalar_key(value: Any) -> str:
    """Stable text representation for validation signatures only."""
    if value is None:
        return "<NULL>"
    try:
        if pd.isna(value):
            return "<NULL>"
    except Exception:
        pass

    if isinstance(value, float):
        if math.isnan(value):
            return "<NULL>"
        return repr(value)

    return str(value)


def coordinate_signature(columns: list[str], row: pd.Series) -> str:
    """
    Canonical validation signature based on dimension name + raw member value.

    This signature is only used to test whether the persisted source
    table has duplicate statistical coordinates after technical value columns
    are removed.
    """
    parts = []
    for col in columns:
        parts.append(f"{col}={scalar_key(row[col])}")
    return "\x1f".join(parts)


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


