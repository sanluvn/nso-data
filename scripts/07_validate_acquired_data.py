def structural_audit(
    px_summary: dict[str, Any],
    website_summary: dict[str, Any],
) -> list[tuple[str, str, str]]:
    """
    Return rows: (assumption, status, evidence/reason).

    PASS means current persisted evidence satisfies the structural check.
    REVIEW means the acquired corpus exposes an exception that should be investigated.
    """
    audit = []

    audit.append(
        (
            "PX tables have valid variable N-dimensional coordinates",
            "PASS" if px_summary["table_count"] == EXPECTED_PX_TABLES else "REVIEW",
            (
                f"{px_summary['table_count']} tables; "
                f"dimension range {px_summary['min_dim']}..{px_summary['max_dim']}"
            ),
        )
    )

    audit.append(
        (
            "PX coordinate signatures do not suffer observed SHA-256 collisions",
            "PASS" if px_summary["collision_tables"] == 0 else "REVIEW",
            f"tables with observed collision={px_summary['collision_tables']}",
        )
    )

    audit.append(
        (
            "PX source rows are unique on all non-technical columns",
            "PASS" if px_summary["duplicate_tables"] == 0 else "REVIEW",
            f"tables with duplicate full source coordinates={px_summary['duplicate_tables']}",
        )
    )

    audit.append(
        (
            "PX dimensions do not require NULL-as-member semantics",
            "PASS" if px_summary["null_dimension_tables"] == 0 else "REVIEW",
            f"tables with NULL dimension cells={px_summary['null_dimension_tables']}",
        )
    )

    audit.append(
        (
            "Website recurring releases provide readable repeated workbook instances",
            "PASS" if website_summary["readable"] > 1 else "REVIEW",
            (
                f"recent XLSX readable={website_summary['readable']}; "
                f"sheet-count distribution={website_summary['sheet_count_distribution']}"
            ),
        )
    )

    audit.append(
        (
            "Website workbooks contain formulas that acquisition must preserve",
            "PASS" if website_summary["formula_workbooks"] > 0 else "REVIEW",
            f"recent workbooks with formulas={website_summary['formula_workbooks']}",
        )
    )

    audit.append(
        (
            "Website workbooks contain ditto notation that acquisition must preserve",
            "PASS" if website_summary["ditto_workbooks"] > 0 else "REVIEW",
            f"recent workbooks with ditto cells={website_summary['ditto_workbooks']}",
        )
    )

    audit.append(
        (
            "Website workbooks contain merged-cell physical layout",
            "PASS" if website_summary["merged_workbooks"] > 0 else "REVIEW",
            f"recent workbooks with merged cells={website_summary['merged_workbooks']}",
        )
    )

    audit.append(
        (
            "Website workbooks contain non-trivial temporal/header text",
            "PASS" if website_summary["temporal_workbooks"] > 0 else "REVIEW",
            f"recent workbooks with temporal header/text evidence={website_summary['temporal_workbooks']}",
        )
    )

    return audit


