TEMPORAL_TERMS = (
    "thang",
    "quy",
    "nam",
    "cung ky",
    "so voi",
    "yoy",
    "luy ke",
    "thuc hien",
)

UNIT_TERMS = (
    "don vi",
    "dvt",
    "%",
    "tan",
    "m3",
    "lit",
    "kwh",
    "dong",
    "cai",
    "chiec",
    "doi",
    "nguoi",
    "doanh nghiep",
)


@dataclass
class SheetEvidence:
    workbook: Path
    sheet: str
    max_row: int
    max_column: int
    merged_ranges: int
    formula_cells: int
    ditto_cells: int
    temporal_text_cells: int
    unit_like_text_cells: int
    nonempty_cells: int
    hierarchy_channel_rows: int


def cell_text(value: Any) -> str:
    return " ".join(str(value).split()) if value is not None else ""


def inspect_sheet_evidence(ws) -> SheetEvidence:
    formula_cells = 0
    ditto_cells = 0
    temporal_text_cells = 0
    unit_like_text_cells = 0
    nonempty_cells = 0

    # Evidence of hierarchical presentation channels: in the first four
    # columns, count rows with text in at least one channel. This does not
    # assert fixed hierarchy levels; it only detects presentation structure.
    hierarchy_channel_rows = 0

    for row in ws.iter_rows():
        first_four_text = 0

        for cell in row:
            value = cell.value
            if value is None:
                continue

            nonempty_cells += 1

            if isinstance(value, str):
                stripped = value.strip()

                if stripped.startswith("="):
                    formula_cells += 1

                if stripped in {'"', "''", "”", "“"}:
                    ditto_cells += 1

                n = norm_text(stripped)
                if any(term in n for term in TEMPORAL_TERMS):
                    temporal_text_cells += 1

                if any(term in n for term in UNIT_TERMS):
                    unit_like_text_cells += 1

                if cell.column <= 4 and stripped:
                    first_four_text += 1

            # openpyxl formulas are strings beginning with "=" when
            # data_only=False. Keep this second check for safety.
            elif getattr(cell, "data_type", None) == "f":
                formula_cells += 1

        if first_four_text:
            hierarchy_channel_rows += 1

    return SheetEvidence(
        workbook=Path(ws.parent.properties.title or ""),
        sheet=ws.title,
        max_row=ws.max_row,
        max_column=ws.max_column,
        merged_ranges=len(ws.merged_cells.ranges),
        formula_cells=formula_cells,
        ditto_cells=ditto_cells,
        temporal_text_cells=temporal_text_cells,
        unit_like_text_cells=unit_like_text_cells,
        nonempty_cells=nonempty_cells,
        hierarchy_channel_rows=hierarchy_channel_rows,
    )


def select_recent_xlsx(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    xlsx = [r for r in records if r["path"].suffix.casefold() == ".xlsx"]
    xlsx.sort(
        key=lambda r: (r["publication_date"], str(r["path"])),
        reverse=True,
    )
    return xlsx[:RECENT_XLSX_LIMIT]


def inspect_recent_workbooks(
    records: list[dict[str, Any]],
) -> dict[str, Any]:
    selected = select_recent_xlsx(records)

    print(f"Recent XLSX selected                  : {len(selected)}")
    if not selected:
        raise RuntimeError("No current .xlsx files available for Website validation.")

    sheet_name_counter = Counter()
    sheet_count_distribution = Counter()
    sheet_evidence: list[dict[str, Any]] = []
    workbook_failures = []
    formula_workbooks = 0
    ditto_workbooks = 0
    merged_workbooks = 0
    temporal_workbooks = 0
    hierarchy_workbooks = 0

    for rec in selected:
        path = rec["path"]

        try:
            wb = load_workbook(
                path,
                read_only=False,
                data_only=False,
            )
        except Exception as exc:
            workbook_failures.append((path, repr(exc)))
            continue

        workbook_has_formula = False
        workbook_has_ditto = False
        workbook_has_merge = False
        workbook_has_temporal = False
        workbook_has_hierarchy = False

        sheet_count_distribution[len(wb.sheetnames)] += 1

        for ws in wb.worksheets:
            sheet_name_counter[compact_text(ws.title)] += 1

            ev = inspect_sheet_evidence(ws)
            ev_dict = {
                "workbook": path,
                "sheet": ws.title,
                "max_row": ev.max_row,
                "max_column": ev.max_column,
                "merged_ranges": ev.merged_ranges,
                "formula_cells": ev.formula_cells,
                "ditto_cells": ev.ditto_cells,
                "temporal_text_cells": ev.temporal_text_cells,
                "unit_like_text_cells": ev.unit_like_text_cells,
                "nonempty_cells": ev.nonempty_cells,
                "hierarchy_channel_rows": ev.hierarchy_channel_rows,
            }
            sheet_evidence.append(ev_dict)

            workbook_has_formula |= ev.formula_cells > 0
            workbook_has_ditto |= ev.ditto_cells > 0
            workbook_has_merge |= ev.merged_ranges > 0
            workbook_has_temporal |= ev.temporal_text_cells > 0
            workbook_has_hierarchy |= ev.hierarchy_channel_rows > 0

        wb.close()

        formula_workbooks += int(workbook_has_formula)
        ditto_workbooks += int(workbook_has_ditto)
        merged_workbooks += int(workbook_has_merge)
        temporal_workbooks += int(workbook_has_temporal)
        hierarchy_workbooks += int(workbook_has_hierarchy)

    print(f"Recent XLSX readable                  : {len(selected) - len(workbook_failures)}")
    print(f"Workbook failures                     : {len(workbook_failures)}")
    print(f"Workbook sheet-count distribution     : {dict(sorted(sheet_count_distribution.items()))}")
    print(f"Workbooks with formulas               : {formula_workbooks}")
    print(f"Workbooks with ditto cells            : {ditto_workbooks}")
    print(f"Workbooks with merged cells           : {merged_workbooks}")
    print(f"Workbooks with temporal text evidence : {temporal_workbooks}")
    print(f"Workbooks with hierarchy-channel text : {hierarchy_workbooks}")

    if workbook_failures:
        for path, err in workbook_failures:
            print(f"  workbook failure: {safe_rel(path)} -> {err}")

    print("\nRecent workbook inventory:")
    for rec in selected:
        snap = rec["snapshot"]
        print(
            f"- {rec['path'].name} | "
            f"publication={snap.get('publication_date')} | "
            f"reference={snap.get('reference_period')} | "
            f"resolution={rec['resolution_mode']}"
        )

    print("\nMost recurrent normalized sheet-name tokens:")
    for name, count in sheet_name_counter.most_common(MAX_SHEET_EXAMPLES):
        print(f"- {name!r}: {count}/{len(selected)}")

    # Bounded structural examples.
    print("\nBounded sheet evidence:")
    for ev in sheet_evidence[:MAX_SHEET_EXAMPLES]:
        print(
            f"- {ev['workbook'].name} :: {ev['sheet']} | "
            f"shape={ev['max_row']}x{ev['max_column']} | "
            f"merges={ev['merged_ranges']} | "
            f"formulas={ev['formula_cells']} | "
            f"ditto={ev['ditto_cells']} | "
            f"temporal_text={ev['temporal_text_cells']}"
        )

    return {
        "selected": len(selected),
        "readable": len(selected) - len(workbook_failures),
        "failures": len(workbook_failures),
        "sheet_count_distribution": dict(sorted(sheet_count_distribution.items())),
        "formula_workbooks": formula_workbooks,
        "ditto_workbooks": ditto_workbooks,
        "merged_workbooks": merged_workbooks,
        "temporal_workbooks": temporal_workbooks,
        "hierarchy_workbooks": hierarchy_workbooks,
        "sheet_evidence": sheet_evidence,
    }


