def current_revision(artifact: dict[str, Any]) -> dict[str, Any] | None:
    current = artifact.get("current_revision")
    revisions = artifact.get("revisions")
    if not isinstance(revisions, list):
        return None
    for rev in revisions:
        if isinstance(rev, dict) and rev.get("revision_number") == current:
            return rev
    return None


def resolve_current_artifact(
    stored: str,
    manifest_path: Path,
) -> tuple[Path | None, str | None]:
    raw = Path(stored)

    candidates: list[tuple[Path, str]] = []
    if raw.is_absolute():
        candidates.append((raw, "absolute"))
    else:
        candidates.extend(
            [
                (PROJECT_ROOT / raw, "project_relative"),
                (NSO_SERIES_ROOT / raw, "series_relative"),
                (manifest_path.parent / raw, "manifest_relative"),
            ]
        )

        # Some stored paths may include the release folder while manifest_path
        # already points inside that release folder.
        if raw.parts and raw.parts[0] == manifest_path.parent.name:
            candidates.append(
                (
                    manifest_path.parent.parent / raw,
                    "manifest_parent_plus_release_relative",
                )
            )

    seen = set()
    for path, mode in candidates:
        key = str(path)
        if key in seen:
            continue
        seen.add(key)
        if path.is_file():
            return path, mode

    return None, None


def production_manifests() -> list[tuple[Path, dict[str, Any]]]:
    out = []
    ignored = 0

    for path in NSO_SERIES_ROOT.rglob("manifest.json"):
        try:
            manifest = load_json(path)
        except Exception:
            ignored += 1
            continue

        if manifest.get("manifest_type") != PRODUCTION_MANIFEST_TYPE:
            ignored += 1
            continue

        out.append((path, manifest))

    print(f"Production manifests                  : {len(out)}")
    print(f"Ignored non-production/invalid        : {ignored}")

    if len(out) != EXPECTED_PRODUCTION_MANIFESTS:
        raise RuntimeError(
            f"Expected {EXPECTED_PRODUCTION_MANIFESTS} production manifests, "
            f"found {len(out)}."
        )

    return out


def current_excel_inventory(
    manifests: list[tuple[Path, dict[str, Any]]],
) -> list[dict[str, Any]]:
    records = []
    missing = []

    for manifest_path, manifest in manifests:
        snapshot = manifest.get("release_snapshot")
        if not isinstance(snapshot, dict):
            snapshot = {}

        for artifact in manifest.get("artifacts", []):
            if not isinstance(artifact, dict):
                continue
            if artifact.get("artifact_type") != "excel":
                continue

            rev = current_revision(artifact)
            if rev is None:
                missing.append((manifest_path, "missing current revision"))
                continue

            stored = rev.get("local_relative_path")
            if not isinstance(stored, str) or not stored.strip():
                missing.append((manifest_path, "missing local_relative_path"))
                continue

            physical, resolution_mode = resolve_current_artifact(stored, manifest_path)
            if physical is None:
                missing.append((manifest_path, stored))
                continue

            records.append(
                {
                    "manifest_path": manifest_path,
                    "manifest": manifest,
                    "snapshot": snapshot,
                    "artifact": artifact,
                    "revision": rev,
                    "path": physical,
                    "resolution_mode": resolution_mode,
                    "publication_date": parse_date(snapshot.get("publication_date")),
                }
            )

    print(f"Current Excel artifacts resolved      : {len(records)}")
    print(f"Current Excel resolution failures     : {len(missing)}")

    if missing:
        for item in missing[:MAX_EXAMPLES]:
            print(f"  unresolved: {item}")

    if len(records) != EXPECTED_CURRENT_EXCEL_ARTIFACTS:
        raise RuntimeError(
            f"Expected {EXPECTED_CURRENT_EXCEL_ARTIFACTS} current Excel artifacts, "
            f"resolved {len(records)}."
        )

    return records


