@dataclass
class PxTableResult:
    path: Path
    rows: int
    dimensions: list[str]
    dimension_count: int
    duplicate_coordinates: int
    null_dimension_cells: int
    signature_collision_count: int
    member_counts: dict[str, int]


def px_parquets() -> list[Path]:
    api_paths = list(
        PX_ROOT.rglob("*.parquet")
    )

    html_paths = list(
        PX_HTML_ROOT.rglob("*.parquet")
    )

    paths = sorted(
        api_paths + html_paths
    )

    if not paths:
        raise RuntimeError(
            "No PX Parquet files found under "
            f"{PX_ROOT} or {PX_HTML_ROOT}"
        )

    return paths

def validate_px_table(path: Path) -> PxTableResult:
    df = pd.read_parquet(path)

    if "value" not in df.columns and "value_raw" not in df.columns:
        raise RuntimeError(
            f"PX table has neither value nor value_raw technical column: {path}"
        )

    dimensions = [c for c in df.columns if c not in PX_TECHNICAL_COLUMNS]

    if not dimensions:
        # A zero-dimensional scalar dataset is theoretically representable,
        # but flag it explicitly because it is unusual in the current corpus.
        dimensions = []

    null_dimension_cells = 0
    member_counts: dict[str, int] = {}
    for col in dimensions:
        null_dimension_cells += int(df[col].isna().sum())
        member_counts[col] = int(df[col].nunique(dropna=False))

    # A statistical source row should be unique on its complete source-native
    # coordinate. Duplicate coordinates would require extra source semantics.
    if dimensions:
        duplicated = df.duplicated(subset=dimensions, keep=False)
        duplicate_coordinates = int(duplicated.sum())
    else:
        duplicate_coordinates = max(0, len(df) - 1)

    # Independently test the signature mechanism and detect theoretical hash
    # collisions inside this table.
    signature_to_coordinate: dict[str, str] = {}
    signature_collision_count = 0

    if dimensions:
        for _, row in df.iterrows():
            coordinate = coordinate_signature(dimensions, row)
            digest = sha256_text(coordinate)
            prior = signature_to_coordinate.get(digest)
            if prior is None:
                signature_to_coordinate[digest] = coordinate
            elif prior != coordinate:
                signature_collision_count += 1
    else:
        digest = sha256_text("<ZERO_DIMENSION_COORDINATE>")
        signature_to_coordinate[digest] = "<ZERO_DIMENSION_COORDINATE>"

    return PxTableResult(
        path=path,
        rows=len(df),
        dimensions=dimensions,
        dimension_count=len(dimensions),
        duplicate_coordinates=duplicate_coordinates,
        null_dimension_cells=null_dimension_cells,
        signature_collision_count=signature_collision_count,
        member_counts=member_counts,
    )


def validate_all_px() -> list[PxTableResult]:
    paths = px_parquets()

    subheading("PX persisted inventory")
    print(f"PX root                              : {PX_ROOT}")
    print(f"Parquet tables discovered            : {len(paths)}")
    print(f"Expected persisted PX tables         : {EXPECTED_PX_TABLES}")

    if len(paths) != EXPECTED_PX_TABLES:
        raise RuntimeError(
            f"Expected {EXPECTED_PX_TABLES} PX Parquet tables, found {len(paths)}."
        )

    results = []
    for i, path in enumerate(paths, start=1):
        result = validate_px_table(path)
        results.append(result)

        if i % 50 == 0 or i == len(paths):
            print(f"Validated PX tables                  : {i}/{len(paths)}")

    return results


def report_px(results: list[PxTableResult]) -> dict[str, Any]:
    subheading("PX N-dimensional representability")

    dim_distribution = Counter(r.dimension_count for r in results)
    max_dim = max((r.dimension_count for r in results), default=0)
    min_dim = min((r.dimension_count for r in results), default=0)
    total_rows = sum(r.rows for r in results)
    dup_tables = [r for r in results if r.duplicate_coordinates > 0]
    null_dim_tables = [r for r in results if r.null_dimension_cells > 0]
    collision_tables = [r for r in results if r.signature_collision_count > 0]

    print(f"Total PX rows                         : {total_rows:,}")
    print(f"Minimum dimensions/table              : {min_dim}")
    print(f"Maximum dimensions/table              : {max_dim}")
    print(f"Dimension-count distribution          : {dict(sorted(dim_distribution.items()))}")
    print(f"Tables with duplicate coordinates     : {len(dup_tables)}")
    print(f"Tables with NULL dimension cells      : {len(null_dim_tables)}")
    print(f"Tables with SHA-256 signature collision: {len(collision_tables)}")

    widest = sorted(
        results,
        key=lambda r: (r.dimension_count, r.rows),
        reverse=True,
    )[:MAX_EXAMPLES]

    print("\nWidest PX table examples:")
    for r in widest:
        print(
            f"- {safe_rel(r.path)} | rows={r.rows:,} | "
            f"dims={r.dimension_count} | {r.dimensions}"
        )

    if dup_tables:
        print("\nPX duplicate-coordinate exceptions:")
        for r in dup_tables[:MAX_EXAMPLES]:
            print(
                f"- {safe_rel(r.path)} | "
                f"duplicate rows={r.duplicate_coordinates:,} | dims={r.dimensions}"
            )

    if null_dim_tables:
        print("\nPX NULL-dimension examples:")
        for r in null_dim_tables[:MAX_EXAMPLES]:
            print(
                f"- {safe_rel(r.path)} | "
                f"NULL dimension cells={r.null_dimension_cells:,}"
            )

    return {
        "table_count": len(results),
        "total_rows": total_rows,
        "min_dim": min_dim,
        "max_dim": max_dim,
        "dim_distribution": dict(sorted(dim_distribution.items())),
        "duplicate_tables": len(dup_tables),
        "null_dimension_tables": len(null_dim_tables),
        "collision_tables": len(collision_tables),
    }


